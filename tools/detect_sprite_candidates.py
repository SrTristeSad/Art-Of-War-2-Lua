#!/usr/bin/env python3
"""Research-only detection of opaque pixel islands, NEVER original animation data.

Groups 8-connected pixels in the 67 supplied RGBA atlases. Transparency may
split a single sprite into many candidates or merge neighboring sprites; every
box must be reviewed against the running J2ME game before use.
"""
import argparse
import csv
import io
from collections import deque
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets' / 'original'
CSV_PATH = ROOT / 'docs' / 'ATLAS_CANDIDATOS.csv'
LUA_PATH = ROOT / 'src' / 'atlas_candidates.lua'
MIN_PIXELS = 12
MAX_PER_ATLAS = 256


def components(image, min_pixels=MIN_PIXELS, limit=MAX_PER_ATLAS):
    rgba = image.convert('RGBA')
    width, height = rgba.size
    alpha = rgba.getchannel('A').tobytes()
    seen = bytearray(width * height)
    found = []
    for start, opacity in enumerate(alpha):
        if opacity == 0 or seen[start]:
            continue
        seen[start] = 1
        q = deque([start]);count = 0
        minx, miny = width, height
        maxx = maxy = 0
        while q:
            p = q.popleft()
            x, y = p % width, p // width
            count += 1
            minx = min(minx, x);maxx = max(maxx, x)
            miny = min(miny, y);maxy = max(maxy, y)
            for yy in range(max(0, y-1), min(height-1, y+1)+1):
                for xx in range(max(0, x-1), min(width-1, x+1)+1):
                    n = yy*width+xx
                    if not seen[n] and alpha[n] != 0:
                        seen[n] = 1;q.append(n)
        w, h = maxx-minx+1, maxy-miny+1
        if count >= min_pixels and w >= 2 and h >= 2:
            found.append((minx, miny, w, h, count))
    # Prioritize sizable visible shapes, while keeping atlas source coordinates.
    found.sort(key=lambda v: (-v[4], v[1], v[0]))
    return sorted(found[:limit], key=lambda v: (v[1], v[0]))


def render(files):
    csv_buffer = io.StringIO(newline='')
    writer = csv.writer(csv_buffer, lineterminator='\n')
    writer.writerow(['atlas','x','y','width','height','opaque_pixels','verification'])
    lines = ['-- GENERATED by tools/detect_sprite_candidates.py. Research only.',
             '-- A component is NOT a proven sprite or animation frame.',
             'return {']
    total = 0
    for f in files:
        with Image.open(f) as source:
            comps = components(source)
        lines.append('  ["'+f.name+'"] = {')
        for x,y,w,h,count in comps:
            writer.writerow([f.name,x,y,w,h,count,'unverified'])
            lines.append('    {x=%d,y=%d,w=%d,h=%d,pixels=%d},' % (x,y,w,h,count))
        lines.append('  },')
        total += len(comps)
    lines.append('}')
    return csv_buffer.getvalue(), '\n'.join(lines)+'\n', total


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true', help='check generated files without changing them')
    args = parser.parse_args()
    files = sorted(SOURCE.glob('*.png'))
    if len(files) != 67:
        raise SystemExit('Expected exactly 67 original PNGs, found %d' % len(files))
    csv_text,lua_text,total = render(files)
    if args.verify:
        for f,expected in ((CSV_PATH,csv_text),(LUA_PATH,lua_text)):
            if not f.exists() or f.read_text(encoding='utf-8')!=expected:
                raise SystemExit('STALE candidate index: %s' % f)
    else:
        CSV_PATH.write_text(csv_text,encoding='utf-8')
        LUA_PATH.write_text(lua_text,encoding='utf-8')
    print('%s: %d UNVERIFIED regions / %d source atlases' % ('verified' if args.verify else 'generated',total,len(files)))

if __name__ == '__main__': main()
